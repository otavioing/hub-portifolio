function criarCardProduto(produto) {
    const article = document.createElement("article");
    article.className = "bg-surface-container-lowest rounded-xl overflow-hidden soft-shadow group flex flex-col relative transition-transform duration-300 hover:-translate-y-1 cursor-pointer";
    article.dataset.id = produto.id;
    article.dataset.categorias = produto.categorias.join(",");
    article.tabIndex = 0;
    article.setAttribute("role", "link");
    article.setAttribute("aria-label", `Ver detalhes de ${produto.nome}`);

    article.innerHTML = `
        <div class="aspect-square bg-surface-container relative overflow-hidden">
            <img class="w-full h-full object-cover group-hover:scale-105 transition-transform duration-500"
                alt="${produto.nome}"
                src="${produto.imagem}" />
        </div>
        <div class="p-6 flex flex-col flex-grow">
            <h3 class="font-headline-md text-headline-md text-on-background mb-2">${produto.nome}</h3>
            <p class="font-body-md text-body-md text-on-surface-variant mb-6 flex-grow">${produto.descricao}</p>
            <a class="w-full bg-primary text-on-primary font-label-md text-label-md py-3 px-6 rounded-full hover:opacity-90 transition-opacity active:scale-[0.98] text-center"
                href="produto.html?id=${produto.id}">
                Ver Detalhes
            </a>
        </div>
    `;

    article.addEventListener("click", (event) => {
        if (event.target.closest("a")) {
            return;
        }

        window.location.href = `produto.html?id=${produto.id}`;
    });

    article.addEventListener("keydown", (event) => {
        if (event.key !== "Enter" && event.key !== " ") {
            return;
        }

        event.preventDefault();
        window.location.href = `produto.html?id=${produto.id}`;
    });

    return article;
}

function sortearProdutos(quantidade) {
    const produtosEmbaralhados = [...produtos];

    for (let index = produtosEmbaralhados.length - 1; index > 0; index -= 1) {
        const randomIndex = Math.floor(Math.random() * (index + 1));
        [produtosEmbaralhados[index], produtosEmbaralhados[randomIndex]] = [produtosEmbaralhados[randomIndex], produtosEmbaralhados[index]];
    }

    return produtosEmbaralhados.slice(0, quantidade);
}

function montarHighlightsCatalogo() {
    const highlightProducts = document.querySelector("#highlight-products");

    if (!highlightProducts) {
        return;
    }

    highlightProducts.replaceChildren(...sortearProdutos(3).map(criarCardProduto));
}

function montarCatalogo(listaProdutos) {
    const productGrid = document.querySelector("#product-grid");

    if (!productGrid) {
        return;
    }

    if (listaProdutos.length === 0) {
        productGrid.innerHTML = `
            <div class="col-span-full bg-surface-container-lowest rounded-xl soft-shadow p-8 text-center">
                <span class="material-symbols-outlined text-primary text-4xl mb-3">search_off</span>
                <p class="font-headline-md text-headline-md text-on-surface mb-2">Nenhum produto encontrado</p>
                <p class="font-body-md text-body-md text-on-surface-variant">Tente outra busca ou escolha uma categoria diferente.</p>
            </div>
        `;
        return;
    }

    productGrid.replaceChildren(...listaProdutos.map(criarCardProduto));
}

function normalizarTexto(texto) {
    return texto
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "");
}

function obterCategoriaSelecionada() {
    const categoriaSelecionada = document.querySelector('input[name="category"]:checked');
    return categoriaSelecionada ? categoriaSelecionada.value : "Todos";
}

function filtrarProdutos() {
    const searchInput = document.querySelector("#catalogo-search");
    const termoBusca = normalizarTexto(searchInput ? searchInput.value.trim() : "");
    const categoria = obterCategoriaSelecionada();

    atualizarCategoriaAtiva(categoria);

    const produtosFiltrados = produtos.filter((produto) => {
        const correspondeCategoria = categoria === "Todos" || produto.categorias.includes(categoria);
        const textoProduto = normalizarTexto([
            produto.nome,
            produto.descricao,
            produto.materiais,
            produto.dimensoes,
            produto.cuidados,
            produto.categorias.join(" ")
        ].join(" "));
        const correspondeBusca = termoBusca === "" || textoProduto.includes(termoBusca);

        return correspondeCategoria && correspondeBusca;
    });

    montarCatalogo(produtosFiltrados);
}

function atualizarCategoriaAtiva(categoriaAtiva) {
    document.querySelectorAll('input[name="category"]').forEach((input) => {
        const label = input.closest("label");
        const texto = label ? label.querySelector("span") : null;

        if (!texto) {
            return;
        }

        const ativo = input.value === categoriaAtiva;
        texto.classList.toggle("text-primary", ativo);
        texto.classList.toggle("font-medium", ativo);
        texto.classList.toggle("text-on-surface-variant", !ativo);
    });
}

function prepararFiltrosCatalogo() {
    const productGrid = document.querySelector("#product-grid");

    if (!productGrid) {
        return;
    }

    document.querySelectorAll('input[name="category"]').forEach((input) => {
        input.addEventListener("change", filtrarProdutos);
    });

    const searchInput = document.querySelector("#catalogo-search");

    if (searchInput) {
        searchInput.addEventListener("input", filtrarProdutos);
    }

    filtrarProdutos();
}

function definirTexto(seletor, texto) {
    const elemento = document.querySelector(seletor);

    if (elemento) {
        elemento.textContent = texto;
    }
}

function montarGaleriaProduto(produto) {
    const mainImage = document.querySelector("#main-image");
    const thumbnails = document.querySelector("#product-thumbnails");

    if (!mainImage || !thumbnails) {
        return;
    }

    mainImage.src = produto.imagens[0] || produto.imagem;
    mainImage.alt = produto.nome;
    thumbnails.innerHTML = "";

    produto.imagens.forEach((imagem, index) => {
        const button = document.createElement("button");
        button.className = `aspect-square bg-surface-container-lowest rounded-lg overflow-hidden transition-opacity hover:opacity-100 ${index === 0 ? "border-2 border-primary/30 opacity-100" : "border border-outline-variant/30 opacity-60"}`;
        button.type = "button";
        button.innerHTML = `<img class="w-full h-full object-cover" alt="${produto.nome} - imagem ${index + 1}" src="${imagem}" />`;

        button.addEventListener("click", () => {
            mainImage.src = imagem;
            mainImage.alt = `${produto.nome} - imagem ${index + 1}`;

            thumbnails.querySelectorAll("button").forEach((item) => {
                item.classList.remove("border-2", "border-primary/30", "opacity-100");
                item.classList.add("border", "border-outline-variant/30", "opacity-60");
            });

            button.classList.remove("border", "border-outline-variant/30", "opacity-60");
            button.classList.add("border-2", "border-primary/30", "opacity-100");
        });

        thumbnails.appendChild(button);
    });
}

function montarPaginaProduto() {
    const produtoPage = document.querySelector("#produto-page");

    if (!produtoPage) {
        return;
    }

    const id = Number(new URLSearchParams(window.location.search).get("id"));
    const produto = produtos.find((item) => item.id === id) || produtos[0];

    document.title = `Mimos de Bebê - ${produto.nome}`;
    definirTexto("#product-category", produto.categorias[0]);
    definirTexto("#product-name", produto.nome);
    definirTexto("#product-description", produto.descricao);
    definirTexto("#product-materials", produto.materiais);
    definirTexto("#product-dimensions", produto.dimensoes);
    definirTexto("#product-care", produto.cuidados);
    montarGaleriaProduto(produto);

    const whatsappButton = document.querySelector("#whatsapp-cta");

    if (whatsappButton) {
        whatsappButton.addEventListener("click", () => {
            const message = encodeURIComponent(`Olá! Gostaria de encomendar o produto ${produto.nome}.`);
            alert(`Simulação de envio WhatsApp:\n\n${decodeURIComponent(message)}`);
        });
    }
}

document.addEventListener("DOMContentLoaded", () => {
    prepararFiltrosCatalogo();
    montarHighlightsCatalogo();
    montarPaginaProduto();
});
